#!/usr/bin/env python3
"""Regenerates src/sim_aliases.odin: one `Name :: sim.Name` line per top-level declaration in src/sim.

Transitional shim for the package split (docs/BUILD_PLAN.md, P0). It lets package main keep
using simulation names unqualified while files move into src/sim one slice at a time. An Odin
`::` alias names the same entity (not a copy), so behaviour is unchanged. Delete lines as call
sites in main switch to `sim.Name`; delete the file once none are left.

usage: python3 -I tools/gen_sim_aliases.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIM = ROOT / "src" / "sim"
OUT = ROOT / "src" / "sim_aliases.odin"

DECL = re.compile(r"^([A-Za-z_]\w*)\s*::", re.M)
PRIVATE = re.compile(r"^@\(private[^)]*\)\s*\n?\s*([A-Za-z_]\w*)\s*::", re.M)


def strip(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def main() -> int:
    names: list[str] = []
    for path in sorted(SIM.glob("*.odin")):
        if path.name.endswith("_test.odin"):
            continue
        text = strip(path.read_text())
        if re.search(r"^#\+private", text, re.M):
            continue
        private = set(PRIVATE.findall(text))
        for name in DECL.findall(text):
            if name not in private and name not in names:
                names.append(name)

    lines = [
        "package main",
        "",
        "// GENERATED by tools/gen_sim_aliases.py from src/sim. Do not edit by hand.",
        "// Transitional shim for the package split; see docs/BUILD_PLAN.md (P0).",
        "",
        'import sim "sim"',
        "",
    ]
    width = max(len(n) for n in names)
    lines += [f"{n.ljust(width)} :: sim.{n}" for n in names]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"[ALIASES] {len(names)} names -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
